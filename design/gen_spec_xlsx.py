FONT = "맑은 고딕"
GRAY = PatternFill("solid", fgColor="D9D9D9")      # 머리글
LIGHT = PatternFill("solid", fgColor="F3F3F3")     # 묶음 행
BLUE = PatternFill("solid", fgColor="A4C2F4")      # 간트 막대
SECTION = PatternFill("solid", fgColor="E8EEF9")
THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
WRAP = Alignment(wrap_text=True, vertical="top")
CENTER = Alignment(horizontal="center", vertical="center", wrap_text=True)


def style(cell, bold=False, fill=None, align=WRAP, border=True, size=10):
    cell.font = Font(name=FONT, size=size, bold=bold)
    cell.alignment = align
    if fill:
        cell.fill = fill
    if border:
        cell.border = BORDER


def title(ws, text, ncols):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=ncols)
    c = ws.cell(1, 1, text)
    style(c, bold=True, fill=GRAY, align=CENTER, size=12)
    ws.row_dimensions[1].height = 24


def table_sheet(wb, name, heading, headers, rows, widths, group_cols=0):
    """머리글 한 줄 + 데이터 행으로 된 일반 명세서 시트. group_cols 개의 왼쪽 열은 값이 같으면 비워 둔다(묶음 표시)."""
    ws = wb.create_sheet(name)
    title(ws, heading, len(headers))
    for i, h in enumerate(headers, start=1):
        style(ws.cell(2, i, h), bold=True, fill=GRAY, align=CENTER)
    prev = [None] * group_cols
    for r, row in enumerate(rows, start=3):
        for i, v in enumerate(row, start=1):
            if i <= group_cols:
                same = all(row[k] == prev[k] for k in range(i)) if r > 3 else False
                if same:
                    v = None
                else:
                    prev[i - 1] = row[i - 1]
                    for k in range(i, group_cols):
                        prev[k] = None
            style(ws.cell(r, i, v))
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[L(i)].width = w
    ws.freeze_panes = "A3"
    return ws


