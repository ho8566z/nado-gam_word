def parse_schema(sql):
    tables = []
    for m in re.finditer(r"CREATE TABLE (\w+) \((.*?)\n\);", sql, re.S):
        name, body = m.group(1), m.group(2)
        cols, pk, uks, fks = [], [], [], {}
        for raw in body.split("\n"):
            line = raw.strip().rstrip(",")
            if not line or line.startswith("--"):
                continue
            if line.startswith("PRIMARY KEY"):
                pk = [c.strip() for c in re.search(r"\((.*?)\)", line).group(1).split(",")]
            elif line.startswith("CONSTRAINT"):
                u = re.search(r"UNIQUE \((.*?)\)", line)
                f = re.search(r"FOREIGN KEY \((\w+)\) REFERENCES (\w+) \((\w+)\)", line)
                if u:
                    uks.append([c.strip() for c in u.group(1).split(",")])
                if f:
                    fks[f.group(1)] = f"{f.group(2)}.{f.group(3)}"
            else:
                cm = re.match(r"(\w+)\s+([A-Z]+)(?:\((\d+)(?:,(\d+))?\))?(.*)", line)
                if not cm:
                    continue
                rest = cm.group(5)
                length = cm.group(3) or "-"
                if cm.group(4):
                    length += "," + cm.group(4)
                dm = re.search(r"DEFAULT\s+('[^']*'|\w+(?:\(\))?|\d+)", rest)
                default = dm.group(1).strip("'") if dm else "-"
                if "AUTO_INCREMENT" in rest:
                    default = "AUTO_INCREMENT"
                cols.append({"name": cm.group(1), "type": cm.group(2), "length": length, "default": default,
                             "notnull": "N" if re.search(r"\bNULL\b", rest) and "NOT NULL" not in rest else "Y"})
        for c in cols:
            keys = []
            if c["name"] in pk:
                keys.append("PK")
            if any(len(u) == 1 and u[0] == c["name"] for u in uks):
                keys.append("UK")
            if c["name"] in fks:
                keys.append("FK")
            c["key"] = "/".join(keys) or "-"
            c["fk"] = fks.get(c["name"])
        multi_uk = [u for u in uks if len(u) > 1]
        tables.append((name, cols, multi_uk))
    return tables


